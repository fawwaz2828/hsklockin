/**
 * Semua soal sebagai daftar datar: { id, topic, pieces, end, answer, idT, enT }.
 * Tanda baca akhir (。？！) dipisah dari potongan terakhir supaya tidak membocorkan potongan mana yang di akhir.
 */
export const ORDER_ITEMS = Object.entries(ORDER).flatMap(([topic, [, , , list]]) =>
  list.map(([s, idT, enT], i) => {
    const end = /[。？！]$/.test(s) ? s.slice(-1) : "。";
    const pieces = s.replace(/[。？！]$/, "").split("/").map(x => x.trim());
    return { id: `${topic}-${i}`, topic, pieces, end, answer: pieces.join("") + end, idT, enT };
  }));
